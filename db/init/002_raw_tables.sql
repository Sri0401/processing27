-- Raw layer: data exactly as received from source systems, plus load metadata.
-- Business logic lives in dbt (warehouse/dbt), never here.

-- ---------------------------------------------------------------------------
-- OT telemetry (BMS / smart meters). Hypertable partitioned by time.
-- Primary key makes ingestion idempotent: replays and late corrections upsert.
-- ---------------------------------------------------------------------------
CREATE TABLE raw.meter_reading (
    site_id      text             NOT NULL,
    building_id  text             NOT NULL,
    meter        text             NOT NULL,
    ts           timestamptz      NOT NULL,
    value        double precision NOT NULL,
    unit         text             NOT NULL DEFAULT 'kWh',
    source       text             NOT NULL,   -- 'backfill' | 'stream'
    message_id   uuid,
    ingested_at  timestamptz      NOT NULL DEFAULT now(),
    PRIMARY KEY (building_id, meter, ts)
);
SELECT create_hypertable('raw.meter_reading', by_range('ts', INTERVAL '30 days'));
CREATE INDEX ON raw.meter_reading (ingested_at DESC);

-- Dead-letter table: messages that failed validation, kept for triage/replay.
CREATE TABLE raw.telemetry_reject (
    reject_id    bigserial PRIMARY KEY,
    received_at  timestamptz NOT NULL DEFAULT now(),
    reason       text        NOT NULL,
    payload      jsonb       NOT NULL
);

-- ---------------------------------------------------------------------------
-- Reference data (BDG2 metadata + weather)
-- ---------------------------------------------------------------------------
CREATE TABLE raw.building_metadata (
    building_id              text PRIMARY KEY,
    site_id                  text NOT NULL,
    primary_space_usage      text,
    sub_primary_space_usage  text,
    sqm                      double precision,
    lat                      double precision,
    lng                      double precision,
    timezone                 text,
    year_built               integer,
    number_of_floors         integer,
    occupants                integer,
    has_electricity_meter    boolean,
    has_gas_meter            boolean,
    loaded_at                timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE raw.weather_hourly (
    site_id             text        NOT NULL,
    ts                  timestamptz NOT NULL,
    air_temperature     double precision,
    dew_temperature     double precision,
    cloud_coverage      double precision,
    precip_depth_1hr    double precision,
    sea_lvl_pressure    double precision,
    wind_speed          double precision,
    loaded_at           timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (site_id, ts)
);

-- ---------------------------------------------------------------------------
-- Estates systems (CAFM / condition surveys / access audits).
-- Synthetic - generated by smart_campus.synthetic, see docs/data-sources.md
-- ---------------------------------------------------------------------------
CREATE TABLE raw.asset_register (
    asset_id              text PRIMARY KEY,
    building_id           text    NOT NULL,
    asset_class           text    NOT NULL,
    description           text,
    install_year          integer NOT NULL,
    expected_life_years   integer NOT NULL,
    replacement_cost_gbp  numeric(12, 2) NOT NULL,
    criticality           smallint NOT NULL,     -- 1 = critical, 3 = low
    loaded_at             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE raw.condition_survey (
    survey_id        text PRIMARY KEY,
    asset_id         text NOT NULL,
    survey_date      date NOT NULL,
    condition_grade  char(1) NOT NULL,           -- A (as new) .. D (life expired)
    surveyor         text,
    notes            text,
    loaded_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE raw.work_order (
    work_order_id      text PRIMARY KEY,
    asset_id           text,
    building_id        text NOT NULL,
    raised_at          timestamptz NOT NULL,
    completed_at       timestamptz,
    work_type          text NOT NULL,            -- reactive | planned
    priority           text NOT NULL,            -- P1 .. P4
    category           text NOT NULL,
    description        text,
    labour_cost_gbp    numeric(12, 2),
    material_cost_gbp  numeric(12, 2),
    contractor         text,
    status             text NOT NULL,
    loaded_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE raw.accessibility_audit (
    audit_id                   text PRIMARY KEY,
    building_id                text NOT NULL,
    audit_date                 date NOT NULL,
    check_code                 text NOT NULL,
    check_name                 text NOT NULL,
    result                     text NOT NULL,    -- pass | partial | fail | n/a
    severity                   text NOT NULL,    -- high | medium | low
    remediation_cost_gbp       numeric(12, 2),
    loaded_at                  timestamptz NOT NULL DEFAULT now()
);

-- Grants on the tables above come from the default privileges set in 001.

-- ---------------------------------------------------------------------------
-- Platform health views for the ops dashboard (bi_reader can see these only).
-- ---------------------------------------------------------------------------
CREATE VIEW raw.v_ingest_health AS
SELECT
    date_trunc('minute', ingested_at) AS minute,
    source,
    count(*)                          AS readings,
    max(ingested_at - ts)             AS max_event_lag
FROM raw.meter_reading
WHERE ingested_at > now() - INTERVAL '24 hours'
GROUP BY 1, 2;

CREATE VIEW raw.v_reject_summary AS
SELECT
    date_trunc('minute', received_at) AS minute,
    reason,
    count(*)                          AS rejects
FROM raw.telemetry_reject
WHERE received_at > now() - INTERVAL '24 hours'
GROUP BY 1, 2;

GRANT SELECT ON raw.v_ingest_health, raw.v_reject_summary TO bi_reader;
